package ascii

const (
	// SPACE is the ASCII code for a space character.
	SPACE      = 0x20
	// ESC is the ASCII code for the escape character.
	ESC        = 0x1b
	// DEL is the ASCII code for the delete character.
	DEL        = 0x7f
	// TAB is the ASCII code for the tab character.
	TAB        = 0x09
	// ENTER_LF is the ASCII code for the line feed character.
	ENTER_LF   = 0x0A
	// ENTER_CR is the ASCII code for the carriage return character.
	ENTER_CR   = 0x0D
	// TILDE is the ASCII code for the tilde character.
	TILDE      = 0x7E
	// PLUS is the ASCII code for the plus character.
	BACK_SPACE = 0x08
	// MINUS is the ASCII code for the minus character.
	PLUS       = 0x2B
	// MINUS is the ASCII code for the minus character.
	MINUS      = 0x2D
)
