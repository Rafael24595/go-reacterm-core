package ascii

const (
	// CTRL_A is the ASCII code for the Ctrl+A character.
	CTRL_A = 0x01
	// CTRL_E is the ASCII code for the Ctrl+E character.
	CTRL_E = 0x05
	// CTRL_D is the ASCII code for the Ctrl+D character.
	CTRL_D = 0x04
	// CTRL_C is the ASCII code for the Ctrl+C character.
	CTRL_C = 0x03
	// CTRL_G is the ASCII code for the Ctrl+G character.
	CTRL_G = 0x07
	// CTRL_T is the ASCII code for the Ctrl+T character.
	CTRL_T = 0x14
	// CTRL_W is the ASCII code for the Ctrl+W character.
	CTRL_W = 0x17
)
